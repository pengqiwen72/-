def score_intent_by_keywords(text: str, intent_id: str) -> int:
    """统计文本命中了多少该意图的关键词。"""
    if not text:
        return 0
    lowered = text.lower()
    return sum(1 for kw in INTENT_KEYWORDS.get(intent_id, []) if kw.lower() in lowered)
