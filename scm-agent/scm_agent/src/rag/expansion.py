"""
查询扩展：把客户的口语说法映射到知识库的规范术语。

为什么需要这一层
----------------
纯词法检索（TF-IDF / BM25）有一个跨不过去的坎：**同义词**。

客户说「灯臂**磕碰**了怎么办」，知识库里写的是「**破损**包赔：签收后 48 小时内
提供照片即可赔付」。两句话说的是同一件事，但没有一个字重合。检索结果会
命中别的条款，而且置信度**并不低**——因为查询里的「收到」「怎么处理」这些词
在其他段落里到处都是。这是最危险的一类错误：**答错，且答得很自信**。

这不是调参能解决的。向量检索能缓解，但离线环境跑不了 embedding 服务；
而且真正的客服术语（「破损包赔」「七天无理由」「价保」）是**平台自造词**，
通用 embedding 模型也未必学得好。

所以这里用最直接、也最可控的办法：一张**领域同义词表**。它在生产系统里
是标配——客服知识库的术语和客户的口语之间，永远需要一层人工维护的映射。
表本身放在 `lexicons` 风格的模块里，业务方改词不用碰检索代码。

扩展而不是替换
--------------
命中的同义词是**追加**到查询词里，不替换原词。原因是原词本身可能也有区分度：
「杯子磕碰了」既有「磕碰」（→破损）也可能真的在问「杯」这个品类。
替换会把品类信息丢掉，追加则两个信号都保留，由 BM25 的 idf 决定谁更重要。
"""

from __future__ import annotations

from typing import Dict, List, Set, Tuple

#: 客户口语 -> 知识库规范术语。
#: 键是客户可能说的词，值是知识库里实际使用的说法（可以有多个）。
#: 维护原则：只收**确实会出现在客户消息里、且与知识库用词不同**的说法，
#: 不要把同义词表写成通用词典——表越大，误扩展越多。
