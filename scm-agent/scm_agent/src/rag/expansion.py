"""
查询扩展：把一线口语说法映射到制度文档的规范术语。

为什么需要这一层
----------------
纯词法检索（TF-IDF / BM25）有一个跨不过去的坎：**同义词**。

车间说「M100023 **断料**了，有没有**平替**」，制度文档里写的是「**替代料**
关系：本物料的替代料清单里找有货的物料」。两句话说的是同一件事，但没有
一个字重合。检索结果会命中别的段落，而且置信度**并不低**——因为查询里的
「有没有」「怎么处理」这些词在其他段落里到处都是。这是最危险的一类错误：
**答错，且答得很自信**。

这不是调参能解决的。向量检索能缓解，但离线环境跑不了 embedding 服务；
而且真正的业务术语（「替代料」「让步接收」「免审批直采」「安全库存线」）
是**企业内部约定**，通用 embedding 模型也未必学得好。

所以这里用最直接、也最可控的办法：一张**领域同义词表**。它在生产系统里
是标配——制度文档的术语和一线口语之间，永远需要一层人工维护的映射。
表本身放在 `lexicons` 风格的模块里，业务方改词不用碰检索代码。

扩展而不是替换
--------------
命中的同义词是**追加**到查询词里，不替换原词。原因是原词本身可能也有区分度：
「钢板断料了」既有「断料」（→替代料）也可能真的在问「钢板」这个品类。
替换会把品类信息丢掉，追加则两个信号都保留，由 BM25 的 idf 决定谁更重要。
"""

from __future__ import annotations

from typing import Dict, List, Set, Tuple

#: 一线口语 -> 知识库规范术语。
#: 键是用户可能说的词，值是知识库里实际使用的说法（可以有多个）。
#: 维护原则：只收**确实会出现在用户消息里、且与知识库用词不同**的说法，
#: 不要把同义词表写成通用词典——表越大，误扩展越多。
